  const LOCALES = [
    { id: "en", label: "EN" }, { id: "fr", label: "FR" },
    { id: "es", label: "ES" }, { id: "ar", label: "AR" },
  ];
  const RTL = new Set(["ar"]);
  const FONT_AR_URL = "https://fonts.googleapis.com/css2?family=Noto+Kufi+Arabic:wght@400;500;700&display=swap";

  function detect() {
    const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
    for (const l of langs) {
      const base = String(l).slice(0, 2).toLowerCase();
      if (DICT[base]) return base;
    }
    return "en";
  }

  let locale = GL.store.get("locale", null) || detect();

  function t(key, vars) {
    let s = DICT[locale]?.[key] ?? DICT.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll("{" + k + "}", String(vars[k]));
    return s;
  }

  function injectArabicFont() {
    if (document.querySelector('link[data-arabic-font]')) return;
    const link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = FONT_AR_URL;
    link.dataset.arabicFont = "1";
    document.head.appendChild(link);
  }

  function apply() {
    document.documentElement.lang = locale;
    document.documentElement.dir = RTL.has(locale) ? "rtl" : "ltr";
    if (RTL.has(locale)) injectArabicFont();
    applyDom();
  }

  /* translate any element marked data-i18n="key" (deferred scripts run post-parse) */
  function applyDom(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach(node => {
      const key = node.dataset.i18n;
      const val = DICT[locale]?.[key] ?? DICT.en?.[key];
      if (val != null) node.textContent = val;
    });
  }

  function setLocale(l, reload) {
    if (!DICT[l]) return false;
    locale = l;
    GL.store.set("locale", l);
    apply();
    if (reload) setTimeout(() => location.reload(), 120);
    return true;
  }

  apply();

  window.I18N = {
    t, setLocale, apply, applyDom,
    locales: LOCALES,
    get locale() { return locale; },
    isRTL: () => RTL.has(locale),
  };
